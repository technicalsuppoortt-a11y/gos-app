import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const catalog=JSON.parse(fs.readFileSync('src/i18n/locales/display-ar.json','utf8'));
const patternCatalog=JSON.parse(fs.readFileSync('src/i18n/locales/patterns-ar.json','utf8'));
const source=ts.transpile(fs.readFileSync('src/i18n/translate.ts','utf8').replace("import catalog from './locales/display-ar.json';",`const catalog=${JSON.stringify(catalog)};`).replace("import patterns from './locales/patterns-ar.json';",`const patterns=${JSON.stringify(patternCatalog)};`),{target:ts.ScriptTarget.ES2023,module:ts.ModuleKind.ESNext});
const {resolveDisplayTranslation:tr}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const displaySource=fs.readFileSync('src/i18n/display.ts','utf8').replace(/^import .*;\r?\n/gm,'');
const isolated=ts.transpile(`const i18n={language:'en',resolvedLanguage:'en',on(){},off(){}}; const useSyncExternalStore=(_subscribe:any,read:any)=>read(); export const testLanguage=(language:string)=>{i18n.language=language;};\n${source}\n${displaySource}`,{target:ts.ScriptTarget.ES2023,module:ts.ModuleKind.ESNext});
const display=await import('data:text/javascript;base64,'+Buffer.from(isolated).toString('base64'));
assert.equal(display.translateText(' Save changes '),' Save changes ','English copy and whitespace remain identical');
display.testLanguage('ar');
assert.equal(display.translateText(' Save changes '),' حفظ التغييرات ');
assert.equal(display.translateText('Customer-authored content'),'Customer-authored content');
assert.equal(display.localizeNode('AM'),'AM','Personal initials remain intact');
assert.equal(display.translateText('AM'),'ص','Time-period labels remain translatable');
const element={type:'input',props:{value:'Draft',name:'status',onChange:()=>{}}};
assert.equal(display.localizeNode(element),element,'Elements, field values and callbacks retain their identity');
assert.deepEqual(display.localizeNode(['Draft',42,null]),['مسودة',42,null]);
display.testLanguage('en');
assert.equal(display.translateText('Draft'),'Draft','Switching back restores English');
assert.equal(tr('Funnel'),'قُمع مبيعات');
assert.equal(tr('Booking'),'حجز المواعيد');
assert.equal(tr('Analytics'),'التحليلات');
assert.equal(tr('Draft'),'مسودة');
assert.equal(tr('DRAFT'),'مسودة');
assert.equal(tr('Add Lesson'),'إضافة درس');
assert.equal(tr('Delete Lesson?'),'حذف درس؟');
assert.equal(tr('Delete Customer supplied name?'),'حذف Customer supplied name؟');
assert.equal(tr('Showing 1–10 of 25'),'عرض 1–10 من 25');
assert.equal(tr('30 minutes'),'30 دقيقة');
assert.equal(tr('12 min ago'),'قبل 12 دقيقة');
assert.equal(tr('Oct 14'),'14 أكتوبر');
assert.equal(tr('Welcome back, Salma!'),'مرحبًا بعودتك، Salma!');
assert.equal(tr('Lesson 4 title'),'عنوان الدرس 4');
assert.equal(tr('Price (Optional)'),'السعر (اختياري)');
assert.equal(tr('SKU_CUSTOM_123'),undefined);
assert.equal(tr('https://example.com'),undefined);
assert.equal(tr('a.user@example.com'),undefined);
for(const [english,arabic]of Object.entries(catalog)) {
  assert.ok(english.trim());assert.ok(arabic.trim());
  assert.match(arabic,/[\u0600-\u06ff]/,`Arabic text missing: ${english}`);
}
const en=JSON.parse(fs.readFileSync('src/i18n/locales/en.json','utf8'));
const ar=JSON.parse(fs.readFileSync('src/i18n/locales/ar.json','utf8'));
assert.deepEqual(Object.keys(en).sort(),Object.keys(ar).sort(),'i18next resource key parity');
console.log(`Localization checks passed: ${Object.keys(catalog).length} catalog entries, patterns, technical-value preservation and resource parity.`);
