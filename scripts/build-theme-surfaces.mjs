import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

// Only app chrome is themed. Authored sites, thumbnails and customer previews
// retain their own palette, even when they are displayed inside an editor.
const excluded = ':where(.aw-live-preview,.aw-asset-image,.aw-step-image,.fb-site-window,.fb-live-preview-frame,.fn-focused-canvas,.pf-page,.pf-thumb,.pf-renderer,.pf-canvas,.bk-public,.bk-preview-frame,.bk-live-preview,.lp-page,.product-live-preview,.pp-live-preview,.cw-live-preview,.checkout-screen,.landing-page,[role=switch],.af-switch,.aw-default,.bk-switch-track,.aw-primary,.aw-primary-split,.button-primary,.bk-button.primary,.cw-button.primary,.st-button.primary,.crm-button.primary)';
const guard = `:not([data-form-theme]):not([data-form-theme] *):not([data-public-asset]):not([data-public-asset] *):not(${excluded}):not(${excluded} *)`;
const files = [];
function visit(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const name = path.join(dir, entry.name);
    if (entry.isDirectory()) visit(name);
    else if (name.endsWith('.css') && !/landing|auth|inbox|preview|theme-surfaces|theme-controls|rtl|route-loading/.test(name)) files.push(name);
  }
}
visit('src/pages');
files.push('src/index.css', 'src/role-dashboards.css');
function token(prop, value) {
  const match = value.match(/^(#[\da-f]{3}|#[\da-f]{6}|#[\da-f]{8}|white|black)$/i);
  if (!match) return null;
  let hex = value.toLowerCase();
  if (hex === 'white') hex = '#ffffff';
  if (hex === 'black') hex = '#000000';
  if (hex.length === 4) hex = '#' + [...hex.slice(1)].map(c => c + c).join('');
  if (hex.length === 9) {
    // Preserve subtle white highlights on brand artwork and photographs.
    if (parseInt(hex.slice(7),16) < 128) return null;
    hex = hex.slice(0,7);
  }
  const rgb = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
  const light = Math.max(...rgb), low = Math.min(...rgb);
  const neutral = light - low < 45;
  if (prop === 'color') {
    if (['#6366f1','#635bff','#7c5cfc','#7c3aed','#7065de','#7669e4','#665bd0'].includes(hex)) return '--ui-accent-text';
    // White is intentional on primary buttons and colored banners.
    if (!neutral || low > 205) return null;
    return light < 100 ? '--ui-text' : light < 160 ? '--ui-text-secondary' : '--ui-text-muted';
  }
  if (prop.startsWith('border') && !prop.includes('radius') && neutral && low > 170) return '--ui-border';
  if (['background', 'background-color'].includes(prop) && neutral && low > 210) {
    return low > 248 ? '--ui-surface' : low > 233 ? '--ui-surface-raised' : '--ui-surface-hover';
  }
  if (['background', 'background-color'].includes(prop) && low > 220 && rgb[2] > rgb[0]) return '--ui-accent-surface';
  return null;
}
const output = postcss.root();
const batches = new Map();
output.append(postcss.comment({ text: 'Generated by scripts/build-theme-surfaces.mjs. Light styles and authored previews are untouched.' }));
let count = 0;
for (const file of files.sort()) {
  const root = postcss.parse(fs.readFileSync(file, 'utf8'));
  root.walkRules(rule => {
    if (/dark|:root|@|\.bk-public|\.bk-preview|\.fb-site|\.fb-live|\.fn-editable|\.fn-inline|\.fn-column|\.pf-canvas|\.aw-live|\.aw-asset-image|\.aw-step-image|\.pp-artwork|\.art-|\.welcome-|\.avatar/.test(rule.selector)) return;
    const declarations = [];
    rule.walkDecls(decl => {
      const name = token(decl.prop, decl.value);
      if (name) declarations.push(postcss.decl({ prop: decl.prop.includes('border') ? 'border-color' : decl.prop, value: `var(${name})` }));
      else if (['background','background-image'].includes(decl.prop) && /gradient\(/.test(decl.value)) {
        const colors = decl.value.match(/#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{3}\b/g) || [];
        if (colors.length && colors.every(color => token('background',color))) {
          const themed = decl.value.replace(/#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{3}\b/g, color => `var(${token('background',color)})`);
          declarations.push(postcss.decl({prop:decl.prop,value:themed}));
        }
      }
      // Border shorthands contain the neutral color as their final token.
      else if (/^border(?:-(?:top|bottom|left|right|inline-start|inline-end))?$/.test(decl.prop)) {
        const color = decl.value.split(/\s+/).at(-1);
        if (token('border-color', color)) declarations.push(postcss.decl({ prop: decl.prop === 'border' ? 'border-color' : `${decl.prop}-color`, value: 'var(--ui-border)' }));
      }
    });
    if (!declarations.length) return;
    const selectors = rule.selectors.filter(s => !s.match(/::|:(?:before|after|first-letter|first-line|placeholder|selection)\b/)).map(s => s.trim());
    if (!selectors.length) return;
    const wrappers = [];
    for (let parent = rule.parent; parent && parent.type !== 'root'; parent = parent.parent) {
      if (parent.type === 'atrule' && ['media', 'supports'].includes(parent.name)) {
        wrappers.push({ name: parent.name, params: parent.params });
      } else if (parent.type === 'atrule') return;
    }
    const specificity = selectors.map(s => [
      (s.match(/#[\w-]+/g) || []).length,
      (s.match(/\.[\w-]+|\[[^\]]+\]|:(?!:)[\w-]+/g) || []).length,
      (s.match(/(?:^|[\s>+~])\w+/g) || []).length,
    ]);
    const key = JSON.stringify([wrappers, specificity, declarations.map(d => [d.prop, d.value])]);
    if (!batches.has(key)) batches.set(key, { wrappers, declarations, selectors: new Set() });
    for (const selector of selectors) batches.get(key).selectors.add(selector);
    count++;
  });
}
for (const { wrappers, declarations, selectors } of batches.values()) {
  let node = postcss.rule({ selector: `html.dark :is(\n  ${[...selectors].join(',\n  ')}\n)${guard}` });
  node.append(declarations);
  for (const config of wrappers) {
    const wrapper = postcss.atRule(config); wrapper.append(node); node = wrapper;
  }
  output.append(node);
}
// Utility classes used by dialogs and portal menus also need theme fallbacks.
for (const [classes, prop, name] of [
  ['.bg-white', 'background-color', '--ui-surface'],
  ['.bg-slate-50,.bg-slate-100,.bg-gray-50,.bg-gray-100', 'background-color', '--ui-surface-raised'],
  ['.text-slate-900,.text-slate-800,.text-gray-900,.text-gray-800', 'color', '--ui-text'],
  ['.text-slate-700,.text-slate-600,.text-gray-700,.text-gray-600', 'color', '--ui-text-secondary'],
  ['.text-slate-500,.text-slate-400,.text-gray-500,.text-gray-400', 'color', '--ui-text-muted'],
  ['.border-slate-200,.border-slate-100,.border-gray-200,.border-gray-100', 'border-color', '--ui-border'],
]) {
  const rule = postcss.rule({ selector: `html.dark :where(.layout-dashboard-shell,.role-shell,[role=dialog],.bk-dialog,.bk-menu,.commerce-select-content) :is(${classes})${guard}` });
  rule.append(postcss.decl({ prop, value: `var(${name})` })); output.append(rule);
}
fs.writeFileSync('src/theme-surfaces.css', output.toString() + '\n');
console.log(`Generated ${count} scoped dark surface rules across ${files.length} stylesheets.`);
