import { createServer } from 'vite';
import { createElement } from 'react';
import { renderToString } from 'react-dom/server';
import { createMemoryRouter, RouterProvider } from 'react-router-dom';
import assert from 'node:assert/strict';

const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = { addEventListener() {}, removeEventListener() {}, location: { origin: 'http://localhost' } };
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const model = await server.ssrLoadModule('/src/pages/commerce/model.ts');
  const { populateCommerceDemo } = await server.ssrLoadModule('/src/pages/commerce/demoData.ts');
  const { courseAnalytics } = await server.ssrLoadModule('/src/pages/commerce/analytics-model.ts');
  const settings = await server.ssrLoadModule('/src/pages/commerce/workspacePreferences.ts');
  const { WorkspaceSettings } = await server.ssrLoadModule('/src/pages/commerce/WorkspaceSettings.tsx');
  const { CheckoutScreen } = await server.ssrLoadModule('/src/pages/commerce/CheckoutScreen.tsx');
  const { StudentManager } = await server.ssrLoadModule('/src/pages/commerce/StudentManager.tsx');
  const { CoursePerformance, ProductOrders, ProductRecentActivity } = await server.ssrLoadModule('/src/pages/commerce/ProductInsights.tsx');
  const { CourseCurriculum } = await server.ssrLoadModule('/src/pages/commerce/CourseAuthoring.tsx');
  const now = new Date('2026-10-11T12:00:00Z');
  const course = populateCommerceDemo(model.hydrateProduct({ ...model.newProduct(), id: 'test-course', type: 'Course', name: 'Marketing Masterclass', price: '€297', config: model.defaultConfig('Course', '€297') }), now);
  const c = course.config;
  assert.equal(c.students.length, 8);
  assert.equal(c.orders.length, 18);
  assert.ok(c.activities.some(a => a.title.includes('Payment received €297')));
  assert.ok(c.activities.some(a => a.title.includes('Course completed')));
  assert.deepEqual(new Set(c.students.map(s => s.status)), new Set(['Active', 'Pending', 'Completed']));
  assert.ok(c.students.every(s => s.sample && s.avatar && s.progress >= 0 && s.progress <= 100));
  assert.ok(c.orders.every(o => o.sample && o.productName === course.name));
  const legacy = { ...course, config: { ...c,
    orders: ['Sarah Ahmed', 'Omar Khaled'].map((customer, i) => ({ id: 'DEMO-test-course-0' + (i + 1), customer, email: (i ? 'omar' : 'sarah') + '@example.com', at: i ? '2026-10-10T14:00:00+03:00' : '2026-10-09T10:30:00+03:00', amount: 297, currency: 'EUR', status: i ? 'Pending' : 'Paid', sample: true })),
    students: [{ id: 'student-test-course-01', name: 'Sarah Ahmed', email: 'sarah@example.com', status: 'Active', progress: 45, enrolledAt: '2026-10-09' }],
  } };
  const upgraded = populateCommerceDemo(legacy, now);
  assert.equal(upgraded.config.orders.length, 18);
  assert.equal(upgraded.config.students.length, 8);
  legacy.config.students[0].progress = 63;
  legacy.config.orders[0].amount = 250;
  const editedLegacy = populateCommerceDemo(legacy, now);
  assert.equal(editedLegacy.config.students[0].progress, 63);
  assert.equal(editedLegacy.config.students.length, 1);
  assert.equal(editedLegacy.config.orders[0].amount, 250);
  assert.equal(editedLegacy.config.orders.length, 2);
  const cleared = populateCommerceDemo({ ...course, config: { ...c, students: [], orders: [], activities: [] } }, now);
  assert.equal(cleared.config.students.length + cleared.config.orders.length + cleared.config.activities.length, 0, 'Deleted records must stay deleted');
  const custom = { ...course, config: { ...c, students: [{ ...c.students[0], sample: false, name: 'Real Student' }], orders: [{ ...c.orders[0], sample: false, amount: 99 }] } };
  const preserved = populateCommerceDemo(custom, now);
  assert.deepEqual(preserved.config.students, custom.config.students);
  assert.deepEqual(preserved.config.orders, custom.config.orders);
  for (const type of ['Service', 'Digital Product']) {
    const demo = populateCommerceDemo(model.hydrateProduct({ ...model.newProduct(), type, id: type, config: model.defaultConfig(type, '€97') }), now);
    assert.ok(demo.config.orders.length && demo.config.activities.length);
    assert.equal(demo.config.students, undefined);
  }
  const a = courseAnalytics(c, 0, now.getTime());
  assert.equal(a.revenue, 15 * 297);
  assert.equal(a.completionRate, 25);
  assert.equal(a.timeline.length, 6);
  assert.equal(a.timeline.reduce((sum, month) => sum + month.revenue, 0), a.revenue);
  assert.equal(courseAnalytics(c, now.getTime() - 7 * 86400000, now.getTime()).orders.length, 3);
  assert.equal(courseAnalytics({ ...c, orders: [], students: [] }, 0, now.getTime()).completionRate, 0);
  assert.equal(courseAnalytics({ ...c, orders: [{ ...c.orders[0], currency: 'USD' }] }, 0, now.getTime()).revenue, 0);
  const preferences = { ...settings.defaultWorkspacePreferences, name: 'Acme Academy', currency: 'USD', taxRate: 14, paypal: false };
  await settings.saveWorkspacePreferences('tenant-a', preferences);
  assert.deepEqual(settings.readWorkspacePreferences('tenant-a'), preferences);
  assert.equal(settings.readWorkspacePreferences('tenant-b').name, 'GOS Store');
  await assert.rejects(settings.saveWorkspacePreferences('tenant-a', { ...preferences, taxRate: 101 }), /Tax rate/);
  await assert.rejects(settings.saveWorkspacePreferences('tenant-a', { ...preferences, redirectUrl: 'javascript:alert(1)' }), /redirect URL/);
  assert.deepEqual(settings.readWorkspacePreferences('tenant-a'), preferences, 'Invalid settings cannot replace saved data');
  const settingsHTML = renderToString(createElement(WorkspaceSettings, { notify() {} }));
  for (const card of ['Store details', 'Payment providers', 'Tax &amp; receipts', 'Checkout preferences']) assert.ok(settingsHTML.includes(card));
  assert.equal((settingsHTML.match(/aria-haspopup="dialog"/g) ?? []).length, 4);
  const checkoutRouter = createMemoryRouter([{ path: '/', element: createElement(CheckoutScreen, { product: course }) }]);
  const checkout = renderToString(createElement(RouterProvider, { router: checkoutRouter }));
  assert.equal((checkout.match(/aria-pressed=/g) ?? []).length, 5);
  assert.match(checkout, /aria-pressed="true"[^>]*class="selected"/);
  assert.ok(!checkout.includes('disabled=""'), 'Payment inputs must accept typing');
  assert.ok(checkout.includes('Mock card number') && checkout.includes('connect a payment provider to accept payments'));
  c.modules = [{ title: 'Introduction', lessons: [{ id: 'welcome', title: 'Welcome', kind: 'Video', duration: '4:00', url: '' }] }];
  const props = { product: course, config: c, experience: c.experience, editing: true, configure() {}, customize() {}, update() {}, error() {}, busy() {}, products: [] };
  const studentsHTML = renderToString(createElement(StudentManager, props));
  assert.equal((studentsHTML.match(/class="ce-student-person"/g) ?? []).length, 8);
  assert.equal((studentsHTML.match(/role="progressbar"/g) ?? []).length, 8);
  assert.ok(studentsHTML.includes('ce-status completed') && studentsHTML.includes('ce-status pending'));
  const analyticsHTML = renderToString(createElement(CoursePerformance, props));
  for (const title of ['Sales Revenue', 'Student Completion Rates', 'Monthly Growth']) assert.ok(analyticsHTML.includes(title));
  assert.match(analyticsHTML, /25% of students completed/);
  assert.ok(renderToString(createElement(ProductOrders, { config: c, course: true })).includes('Marketing Masterclass'));
  assert.ok(renderToString(createElement(ProductRecentActivity, props)).includes('New student enrolled'));
  globalThis.sessionStorage = { getItem: () => '["welcome"]', setItem() {} };
  const curriculumHTML = renderToString(createElement(CourseCurriculum, props));
  assert.match(curriculumHTML, /is-complete/);
  assert.match(curriculumHTML, /value="100"/);
  assert.ok(curriculumHTML.includes('Completed in preview'));
  const { ProductWorkspace } = await server.ssrLoadModule('/src/pages/commerce/ProductWorkspace.tsx');
  const { storageKey } = await server.ssrLoadModule('/src/pages/commerce/repository.ts');
  await settings.saveWorkspacePreferences(storageKey(), preferences);
  const draftRouter = createMemoryRouter([{ path: '/dashboard/products-payments/products/new', element: createElement(ProductWorkspace, { mode: 'create' }) }], { initialEntries: ['/dashboard/products-payments/products/new?type=service&tab=checkout'] });
  const draftHTML = renderToString(createElement(RouterProvider, { router: draftRouter }));
  assert.ok(draftHTML.replaceAll('<!-- -->', '').includes('Tax (14%'), 'Workspace tax defaults must reach new product checkout');
  const paymentMethods = draftHTML.match(/<div class="cp-payment-methods"[\s\S]*?<\/div>/)?.[0];
  assert.ok(paymentMethods && !paymentMethods.includes('PayPal'), 'Disabled workspace provider must not appear in new checkout');
  draftRouter.dispose();
  const { ProductsPayments } = await server.ssrLoadModule('/src/pages/ProductsPayments.tsx');
  const router = createMemoryRouter([{ path: '/dashboard/products-payments', element: createElement(ProductsPayments, { notify() {} }) }], { initialEntries: ['/dashboard/products-payments?tab=settings'] });
  assert.ok(renderToString(createElement(RouterProvider, { router })).includes('Workspace Settings'));
  router.dispose();
  console.log('PASS commerce settings persistence, checkout controls, demo preservation, student tables, lesson progress, analytics and settings route');
} finally { await server.close(); }
