  await add('Tabs','2 items');
  const websiteTabs=page.locator('[data-element-type="Tabs"]');
  await websiteTabs.getByRole('tab',{name:'Tab 2',exact:true}).click();
  assert.equal(await websiteTabs.getByRole('tab',{name:'Tab 2',exact:true}).getAttribute('aria-selected'),'true');
  assert.deepEqual(errors,[]);
  if(process.env.FUNNEL_SCREENSHOT_DIR) await page.screenshot({path:process.env.FUNNEL_SCREENSHOT_DIR+'/editor-elements-qa.png',fullPage:true});
