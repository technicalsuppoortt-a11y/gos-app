  await page.locator('.pf-icon-rail').getByRole('button',{name:'Elements',exact:true}).click();
  const add=async(kind,variant='Default')=>{await page.locator('.fb-block-button').filter({hasText:new RegExp('^'+kind+'$')}).click();await page.locator('.pf-variant-panel').waitFor();await page.locator('.pf-variant-card').filter({hasText:variant}).click();};
  await add('Layouts','1/4 + 1/4 + 1/4 + 1/4');
  assert.equal(await page.locator('.fn-column').count(),4);
  await add('Accordion','3 items');
  const accordion=page.locator('[data-element-type="Accordion"]');
  assert.equal(await accordion.locator('details').count(),3);
