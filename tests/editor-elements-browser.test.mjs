  assert.equal(await accordion.locator('details').nth(1).getAttribute('open'),'');
  await page.getByRole('button',{name:'Add item',exact:true}).click();
  assert.equal(await accordion.locator('details').count(),4);
  await add('Tabs','3 items');
  const tabs=page.locator('[data-element-type="Tabs"]');
  await tabs.getByRole('tab',{name:'Tab 2',exact:true}).click();
  assert.equal(await tabs.getByRole('tab',{name:'Tab 2',exact:true}).getAttribute('aria-selected'),'true');
  await page.getByRole('button',{name:'Move item 2 up'}).click();
  assert.equal(await tabs.getByRole('tab').first().textContent(),'Tab 2');
  await add('Heading');
  const inspector=page.locator('.fb-right-panel');
  await inspector.getByLabel(/^Heading text/).fill('Updated heading');
  await inspector.getByRole('button',{name:'Bold',exact:true}).click();
  await inspector.getByRole('button',{name:'Italic',exact:true}).click();
  await inspector.getByRole('combobox',{name:'HTML tag',exact:true}).click();
  await page.getByRole('option',{name:'H5',exact:true}).click();
  const heading=page.locator('[data-element-type="Heading"]');
  assert.equal(await heading.locator('h5').textContent(),'Updated heading');
  assert.equal(await heading.locator('h5').evaluate(el=>getComputedStyle(el).fontStyle),'italic');
  await inspector.getByRole('button',{name:'Style',exact:true}).click();
  for(const side of ['top','right','bottom','left']) await inspector.getByLabel('Padding '+side,{exact:true}).fill('12');
  await inspector.getByLabel('Margin left',{exact:true}).fill('8');
  assert.equal(await heading.evaluate(el=>getComputedStyle(el).padding),'12px');
  await inspector.getByRole('button',{name:'Advanced',exact:true}).click();
  await inspector.getByLabel('HTML ID',{exact:true}).fill('main-heading');
  await inspector.getByLabel('Hide on mobile',{exact:true}).check();
  await inspector.getByLabel('Hide on tablet',{exact:true}).check();
  assert.equal(await heading.getAttribute('id'),'main-heading');
  await page.getByRole('button',{name:'Save Draft',exact:true}).click();
  await page.reload();await page.locator('.fb-editor-header').waitFor();
  await page.locator('[data-element-type="Heading"]').click();
  await inspector.getByRole('button',{name:'Advanced',exact:true}).click();
  assert.equal(await inspector.getByLabel('Hide on mobile',{exact:true}).isChecked(),true);
  assert.equal(await inspector.getByLabel('Hide on desktop',{exact:true}).isChecked(),false);
  await page.locator('.pf-icon-rail').getByRole('button',{name:'Elements',exact:true}).click();
  await add('Button');
  assert.ok(await page.locator('[data-element-type="Button"] .fb-site-primary').textContent());
  await add('Paragraph');
  assert.ok(await page.locator('[data-element-type="Paragraph"] p').textContent());
  await page.getByRole('button',{name:'Preview',exact:true}).click();
