import {createRequire} from 'node:module';
import {createServer} from 'vite';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const server=await createServer({server:{host:'127.0.0.1',port:5214,strictPort:true}});
await server.listen();let browser;
try {
 browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{if(window!==window.top)return;localStorage.setItem('i18nextLng','en');localStorage.setItem('gos.auth',JSON.stringify({user:{id:'test',email:'test@example.com',name:'Test'},role:'USER',token:'test',tenant:{id:'test',name:'GOS'}}));});
 await page.goto('http://127.0.0.1:5214/dashboard/funnels?tab=templates');
 await page.getByRole('button',{name:'Use Personal coaching template',exact:true}).click();await page.locator('.fb-editor-header').waitFor();
 const inspector=page.locator('.fb-right-panel'),tree=page.locator('.pf-content-tree');
 await tree.locator('.pf-tree-select').filter({hasText:/^Hero$/}).click();
 await inspector.getByLabel('Element name',{exact:true}).fill('Features Section');
 const hero=page.locator('[data-section-id][data-element-type="Hero"]');
 assert.equal(await tree.locator('.pf-tree-select').filter({hasText:/^Features Section$/}).count(),1);
 assert.equal(await hero.locator('.fn-element-actions span').textContent(),'Features Section');
 assert.equal(await inspector.locator('h2').textContent(),'Features Section content');
 const heading=hero.locator('[data-element-part$="::title"]'),originalText=await heading.textContent();
 await heading.click();await inspector.getByLabel('Element name',{exact:true}).fill('Main Headline');
 assert.equal(await page.getByRole('toolbar',{name:'Main Headline selection actions'}).locator('b').textContent(),'Main Headline');
 assert.equal(await inspector.locator('h2').textContent(),'Main Headline content');
 assert.equal(await heading.textContent(),originalText);
 await tree.getByLabel('Search page content').fill('Main Headline');
 assert.equal(await tree.locator('.pf-tree-select').filter({hasText:/^Main Headline$/}).count(),1);
 await tree.getByLabel('Search page content').fill('');
 await page.locator('.pf-icon-rail').getByRole('button',{name:'Elements',exact:true}).click();
 await page.locator('.fb-block-button').filter({hasText:/^HTML\/Liquid$/}).click();await page.locator('.pf-variant-card').click();
 await inspector.getByLabel('Element name',{exact:true}).fill('Custom Banner');
 const html=page.locator('[data-section-id][data-element-type="HTML/Liquid"]');
 assert.equal(await html.locator('.fn-element-actions span').textContent(),'Custom Banner');
 assert.equal(await inspector.locator('h2').textContent(),'Custom Banner content');
 await inspector.getByRole('button',{name:'Open code editor',exact:true}).click();
 await page.getByRole('dialog',{name:'HTML/Liquid code editor'}).getByRole('button',{name:'Cancel',exact:true}).click();
 await inspector.getByLabel('Element name',{exact:true}).fill('');
 assert.equal(await html.locator('.fn-element-actions span').textContent(),'HTML/Liquid');
 await inspector.getByLabel('Element name',{exact:true}).fill('Custom Banner');
 await page.getByRole('button',{name:'Save Draft',exact:true}).click();await page.reload();await page.locator('.fb-editor-header').waitFor();
 await page.locator('.pf-icon-rail').getByRole('button',{name:'Page content',exact:true}).click();
 for(const name of ['Features Section','Main Headline','Custom Banner'])assert.equal(await tree.locator('.pf-tree-select').filter({hasText:new RegExp('^'+name+'$')}).count(),1);
 await tree.locator('.pf-tree-select').filter({hasText:/^Custom Banner$/}).click();
 assert.equal(await inspector.getByLabel('Element name',{exact:true}).inputValue(),'Custom Banner');
 assert.equal(await html.getAttribute('data-element-type'),'HTML/Liquid');
 await tree.locator('.pf-tree-select').filter({hasText:/^Main Headline$/}).click();
 await page.getByRole('toolbar',{name:'Main Headline selection actions'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: names instantly sync across tree, badges and inspector for sections, nested headings and HTML/Liquid; searchable, resettable and saved after reload without changing content or type');
}finally{await browser?.close();await server.close();}
