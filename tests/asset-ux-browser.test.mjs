import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createServer } from 'vite';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.FUNNEL_BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
  const errors = [], submissions = [];
  let failForm = true, missingDomain = true;
  const cors = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': 'content-type,authorization,x-firebase-appcheck', 'Access-Control-Allow-Methods': 'POST,OPTIONS' };
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/captureAssetLead', async route => {
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers: cors });
    submissions.push(route.request().postDataJSON().data);
    await new Promise(resolve => setTimeout(resolve, 350));
    await route.fulfill({ status: failForm ? 503 : 200, headers: cors, contentType: 'application/json', body: JSON.stringify(failForm ? { error: { status: 'UNAVAILABLE', message: 'Please retry this inquiry' } } : { result: { accepted: true, leadId: 'captured' } }) });
  });
  await page.route('**/hostingDomain', async route => {
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers: cors });
    if (missingDomain) return route.fulfill({ status: 404, headers: cors, body: 'Not Found' });
    assert.equal(route.request().postDataJSON().data.operation, 'connect');
    await route.fulfill({ status: 200, headers: cors, contentType: 'application/json', body: JSON.stringify({ result: { domain: { id: 'queued-domain', name: 'preview.example.com', assetId: 'asset', status: 'Connected', ssl: 'Active', default: false } } }) });
  });
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/asset-ux.html`);
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  const publishing = page.getByRole('button', { name: 'Publishing...', exact: true });
  await publishing.waitFor();
  assert.equal(await publishing.isDisabled(), true);
  assert.equal(await publishing.getAttribute('aria-busy'), 'true');
  await publishing.evaluate(button => { button.click(); button.click(); });
  await page.getByRole('button', { name: 'Publish', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.__publishCount), 1);
  await page.getByRole('button', { name: 'Fail save', exact: true }).click();
  await page.getByRole('button', { name: 'Fail save', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Fail save', exact: true }).isEnabled(), true);
  const template = page.locator('.pf-template-card');
  const before = await template.boundingBox();
  await template.click();
  await template.getByText('Creating...', { exact: true }).waitFor();
  const during = await template.boundingBox();
  assert.equal(during.width, before.width); assert.equal(during.height, before.height);
  assert.equal(await template.isDisabled(), true);
  await template.getByText('Use Template', { exact: true }).waitFor();
  const live = page.getByRole('link', { name: 'View Published Site' });
  assert.equal(await live.getAttribute('href'), 'https://published-fixture.web.app/');
  assert.equal(await live.getAttribute('target'), '_blank');
  await page.getByRole('button', { name: 'Queue domain', exact: true }).click();
  await page.getByTestId('pending-domains').filter({ hasText: 'preview.example.com: Pending' }).waitFor();
  missingDomain = false;
  await page.getByRole('button', { name: 'Retry domain', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('[data-testid="pending-domains"]').textContent);
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.getByRole('heading', { name: 'Exact visitor content', exact: true }).waitFor();
  assert.equal(await page.locator('[data-testid="dashboard-sidebar"], [data-testid="workspace-header"], .fb-editor-header').count(), 0);
  assert.equal(await page.locator('.fb-site-frame').evaluate(node => Math.round(node.getBoundingClientRect().width)), 1280);
  const nav = page.locator('.fb-live-page-nav');
  assert.equal(await nav.evaluate(node => getComputedStyle(node).display), 'flex');
  assert.ok(await nav.evaluate(node => node.getBoundingClientRect().height >= 50));
  await page.locator('#contact input[name="name"]').fill('Alex Morgan');
  await page.locator('#contact input[name="email"]').fill('alex@example.com');
  await page.locator('#contact textarea[name="message"]').fill('Please contact me');
  await page.getByRole('button', { name: 'Send inquiry', exact: true }).click();
  await page.getByRole('button', { name: 'Submitting...', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Submitting...', exact: true }).isDisabled(), true);
  await page.getByText('Connection lost. Check your network and try again.', { exact: true }).waitFor();
  assert.equal(await page.locator('#contact input[name="email"]').inputValue(), 'alex@example.com');
  failForm = false;
  await page.getByRole('button', { name: 'Send inquiry', exact: true }).click();
  await page.getByText('Inquiry saved', { exact: true }).waitFor();
  assert.equal(submissions.length, 2);
  assert.equal(submissions[0].requestId, submissions[1].requestId);
  assert.equal(submissions[1].name, 'Alex Morgan'); assert.equal(submissions[1].message, 'Please contact me');
  assert.equal(submissions[1].preview, true);
  const rem = await page.evaluate(() => parseFloat(getComputedStyle(document.documentElement).fontSize));
  await page.getByRole('button', { name: 'Tablet preview', exact: true }).click();
  await page.waitForFunction(width => Math.round(document.querySelector('.fb-site-frame').getBoundingClientRect().width) === width, Math.round(rem * 28));
  await page.getByRole('button', { name: 'Mobile preview', exact: true }).click();
  await page.waitForFunction(width => Math.round(document.querySelector('.fb-site-frame').getBoundingClientRect().width) === width, Math.round(rem * 24));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.fb-site-frame').evaluate(node => Math.round(node.getBoundingClientRect().width)), Math.round(rem * 24));
  await page.getByRole('button', { name: 'Open navigation menu', exact: true }).click();
  await page.getByRole('button', { name: 'Thanks', exact: true }).click();
  await page.getByRole('heading', { name: 'Second visitor page', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to builder', exact: true }).click();
  await page.locator('[data-testid="dashboard-sidebar"]').waitFor();
  assert.deepEqual(errors, []);
  console.log('Loading, duplicate prevention, domain 404 queue/retry, form capture/retry, styled navigation and desktop/tablet/mobile previews passed.');
} finally { await browser?.close(); await server.close(); }
