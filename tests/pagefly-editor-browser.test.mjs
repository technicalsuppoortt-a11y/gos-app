import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const server = await createServer({ server: { host: '127.0.0.1', port: 5203, strictPort: true } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.FUNNEL_BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    localStorage.setItem('i18nextLng', 'en');
    localStorage.setItem('gos.auth', JSON.stringify({ user: { id: 'test', email: 'test@example.com', name: 'Test User' }, role: 'USER', token: 'test', tenant: { id: 'test', name: 'GOS' } }));
  });
  const openCreate = async () => {
    await page.goto('http://127.0.0.1:5203/dashboard/funnels');
    await page.getByRole('button', { name: 'Create Funnel', exact: true }).click();
    await page.getByRole('dialog').waitFor();
  };
  await openCreate();
  await page.getByLabel('Funnel name', { exact: true }).fill('Clean canvas QA');
  if (process.env.FUNNEL_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.FUNNEL_SCREENSHOT_DIR, 'creation-modal.png') });
  await page.getByRole('button', { name: 'Create blank page' }).click();
  await page.locator('.fb-editor-header').waitFor();
  assert.equal(await page.locator('.fn-editable-section').count(), 0);
  assert.equal(await page.locator('.fb-site-topline').count(), 0);
  assert.deepEqual(await page.locator('.pf-icon-rail button').evaluateAll(items => items.slice(0, 3).map(item => item.getAttribute('aria-label'))), ['Page content', 'Elements', 'Third-party elements']);
  await page.getByRole('button', { name: 'Elements', exact: true }).click();
  await page.locator('.fb-block-button').filter({ hasText: /^Columns$/ }).click();
  const transfer = await page.evaluateHandle(() => { const value = new DataTransfer(); value.setData('text/gos-block', 'Heading'); return value; });
  await page.locator('.fn-column .fn-drop-zone.empty').first().dispatchEvent('drop', { dataTransfer: transfer });
  assert.equal(await page.locator('.fn-column [data-element-type="Heading"]').count(), 1);
  await page.getByRole('button', { name: 'Page content', exact: true }).click();
  await page.locator('.pf-tree-select').filter({ hasText: /^Heading$/ }).click();
  assert.equal(await page.locator('.fn-editable-section.selected').getAttribute('data-element-type'), 'Heading');
  await page.getByRole('button', { name: 'Third-party elements', exact: true }).click();
  await page.getByRole('button', { name: 'Manage integrations' }).click();
  await page.locator('.pf-app-manager').getByLabel('Booking', { exact: true }).check();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Booking', exact: true }).click();
  assert.equal(await page.locator('[data-element-type="Booking"]').count(), 1);
  await page.reload();
  await page.locator('.fb-editor-header').waitFor();
  assert.equal(await page.locator('.fn-column [data-element-type="Heading"]').count(), 1);
  await page.getByRole('button', { name: 'Third-party elements', exact: true }).click();
  assert.equal(await page.locator('.pf-app-block').count(), 1);
  await openCreate();
  await page.getByRole('tab', { name: 'Template' }).click();
  assert.equal(await page.locator('.pf-template-card').count(), 6);
  await page.getByLabel('Template industry').selectOption('Fitness');
  await page.getByLabel('Template goal').selectOption('Sales');
  assert.equal(await page.locator('.pf-template-card').count(), 1);
  await page.getByLabel('Template industry').selectOption('All industries');
  await page.getByLabel('Template goal').selectOption('All goals');
  if (process.env.FUNNEL_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.FUNNEL_SCREENSHOT_DIR, 'template-library.png') });
  await page.getByRole('button', { name: 'Use Personal coaching template', exact: true }).click();
  await page.locator('.fb-editor-header').waitFor();
  assert.equal(await page.locator('[data-element-type="Hero"] h1').innerText(), 'Build strength. Build confidence.');
  assert.equal(await page.locator('.fn-column').count(), 3);
  assert.equal(await page.locator('[data-element-type="Form"] input').count(), 2);
  if (process.env.FUNNEL_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.FUNNEL_SCREENSHOT_DIR, 'page-content-editor.png') });
  await page.getByRole('button', { name: 'Elements', exact: true }).click();
  if (process.env.FUNNEL_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.FUNNEL_SCREENSHOT_DIR, 'elements-editor.png') });
  await page.reload();
  await page.locator('[data-element-type="Hero"] h1').waitFor();
  assert.equal(await page.locator('[data-element-type="Hero"] h1').innerText(), 'Build strength. Build confidence.');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.locator('.fb-live-preview-stage').waitFor();
  await page.locator('.fb-live-preview-stage .fb-hero-section button').click();
  assert.equal(await page.locator('.fb-live-action-step').count(), 0, 'Lead template CTA should scroll to its form');
  const previewForm = page.locator('.fb-live-preview-stage .fb-demo-form');
  await previewForm.getByPlaceholder('Your name').fill('Template QA');
  await previewForm.getByPlaceholder('Email', { exact: true }).fill('qa@example.com');
  await previewForm.getByRole('button').click();
  await page.getByText('Thank you! Your request has been received.', { exact: true }).waitFor();
  for (const [name, type] of [['Nutrition consultation', 'Booking'], ['Agency growth', 'Form'], ['Product launch', 'Pricing'], ['Online masterclass', 'Form'], ['Studio membership', 'Pricing']]) {
    await openCreate();
    await page.getByRole('tab', { name: 'Template' }).click();
    await page.getByRole('button', { name: `Use ${name} template`, exact: true }).click();
    await page.locator('.fb-editor-header').waitFor();
    assert.equal(await page.locator(`[data-element-type="${type}"]`).count(), 1, name);
    assert.equal(await page.locator('.fn-column').count(), 3, name);
  }
  await page.goto('http://127.0.0.1:5203/dashboard/websites');
  await page.getByRole('button', { name: 'Create Website', exact: true }).click();
  await page.getByRole('tab', { name: 'Template' }).click();
  await page.getByRole('button', { name: 'Use Personal coaching template', exact: true }).click();
  await page.locator('.fb-editor-header').waitFor();
  await page.locator('.pf-tree-select').filter({ hasText: /^Heading$/ }).first().click();
  assert.equal(await page.locator('.fn-editable-section.selected').getAttribute('data-element-type'), 'Heading', 'Website templates must allow nested editing');
  assert.deepEqual(errors, []);
  console.log('PageFly sidebar, blank creation, template filters, installation, nested drag/drop, selection, app blocks and reload passed.');
} finally { await browser?.close(); await server.close(); }
