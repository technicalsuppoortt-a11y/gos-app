import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createServer } from 'vite';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
const output = await mkdtemp(join(tmpdir(), 'gos-form-modes-'));
await server.listen();
let browser;
try {
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = `http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/form-modes.html`;
  await page.goto(url);
  await page.getByRole('button', { name: 'Advanced Form', exact: true }).click();
  await page.getByLabel('Funnel name', { exact: true }).fill('Advanced retained');
  await page.waitForFunction(() => window.__workspace?.assets[0].document.funnel.name === 'Advanced retained');
  await page.getByRole('button', { name: 'Fast Form', exact: true }).click();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.form-mode-selector button.active')).backgroundColor === 'rgb(124, 58, 237)');
  await page.screenshot({ path: join(output, 'forms-fast-light.png'), fullPage: true });
  await page.getByRole('button', { name: /Single Line Text/ }).click();
  await page.waitForFunction(() => JSON.parse(window.__workspace.assets[0].document.pages[0].sections[0].children[0][0].content.customFields).length === 4);
  await page.getByRole('button', { name: 'Advanced Form', exact: true }).click();
  assert.equal(await page.getByLabel('Funnel name', { exact: true }).inputValue(), 'Advanced retained');
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  assert.equal(await page.locator('.form-advanced-editor [data-form-theme]').getAttribute('data-form-theme'), 'light');
  assert.equal(await page.locator('.form-advanced-editor .fb-field-label').first().evaluate(node => getComputedStyle(node).color), 'rgb(15, 23, 42)');
  await page.screenshot({ path: join(output, 'forms-advanced-dark.png'), fullPage: true });
  await page.goto(`${url}?picker`);
  await page.locator('[data-section-id]').filter({ has: page.locator('form') }).first().click();
  await page.getByRole('combobox', { name: 'Workspace form', exact: true }).click();
  await page.getByRole('option', { name: '+ Create New Form', exact: true }).click();
  await page.waitForFunction(() => window.__created && window.__document.pages.some(p => p.sections.some(s => s.content.formAssetId)));
  await page.getByRole('button', { name: 'Create New Form', exact: true }).click();
  await page.waitForFunction(() => window.__created && window.__document.pages.some(p => p.sections.some(s => s.content.formAssetId)));
  await page.goto(`${url}?steps`);
  await page.getByPlaceholder('About us').fill('Application review');
  await page.getByLabel('Step type', { exact: true }).fill('  Application review  ');
  await page.getByRole('button', { name: /Add Step/ }).last().click();
  await page.waitForFunction(() => window.__document?.steps.some(s => s.type === 'Application review'));
  assert.deepEqual(errors, []);
  console.log(`Form mode retention, theme tokens, nested fields, quick creation connection, and custom step persistence passed. Screenshots: ${output}`);
} finally { await browser?.close(); await server.close(); }
