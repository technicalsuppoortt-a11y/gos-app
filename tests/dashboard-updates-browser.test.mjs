import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/fixtures/dashboard-updates.html`);
  await page.getByRole('button', { name: 'Consultation request', exact: true }).click();
  const editor = page.locator('.forms-workspace');
  assert.equal(await editor.getByLabel('Label', { exact: true }).count(), 5);
  await editor.getByLabel('Pipeline', { exact: true }).selectOption('sales');
  await editor.getByLabel('Initial stage', { exact: true }).selectOption('QUALIFIED');
  await page.waitForFunction(() => window.__workspace.assets[0].crmRouting.pipelineId === 'sales' && window.__workspace.assets[0].crmRouting.stageId === 'QUALIFIED');
  await editor.getByRole('button', { name: 'Add field', exact: true }).click();
  const labels = editor.getByLabel('Label', { exact: true });
  await labels.last().fill('Consent to contact');
  await editor.getByLabel('Type', { exact: true }).last().selectOption('checkbox');
  await editor.getByLabel('Required', { exact: true }).last().check();
  const preview = page.getByRole('region', { name: 'Published form preview' });
  await preview.getByLabel('Name', { exact: false }).fill('Alex Morgan');
  await preview.getByLabel('Email', { exact: false }).fill('alex@example.com');
  await preview.getByLabel('How can we help?', { exact: false }).selectOption('Strategy');
  await preview.getByLabel('Consent to contact', { exact: false }).check();
  await preview.getByRole('button', { name: 'Submit', exact: true }).click();
  await page.waitForFunction(() => window.__submission?.customFields?.service === 'Strategy');
  assert.equal(await page.evaluate(() => window.__submission.email), 'alex@example.com');
  assert.equal(await page.evaluate(() => window.__submission.customFields.name), 'Alex Morgan');
  await page.evaluate(() => window.__makePublished());
  const targetId = await page.evaluate(() => window.__workspace.assets.find(a => !a.formAsset).id);
  await editor.getByLabel('Destination asset', { exact: true }).selectOption(targetId);
  await editor.getByRole('button', { name: 'Embed in selected page', exact: true }).click();
  await page.waitForFunction(() => window.__workspace.assets.find(a => !a.formAsset).document.pages[0].sections.some(s => s.content.publishedFormUrl === 'https://form-fixture.web.app'));
  await mkdir('artifacts/dashboard-updates', { recursive: true });
  await page.screenshot({ path: 'artifacts/dashboard-updates/forms-light.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Forms browser checks passed: templates, custom fields, required checkbox, routing, responsive layout, and actual submission payload.');
} finally { await browser?.close(); await server.close(); }
